<?php
// Company-scoped material purchase orders and their status workflow.
require_once 'dbconnection.php';
if (!headers_sent()) header('Content-Type: application/json; charset=utf-8');
$data = json_decode(file_get_contents('php://input'), true);
if (!is_array($data)) $data = $_POST;
$type = intval($data['type'] ?? 0);
$company_id = mysqli_real_escape_string($sql, trim((string)($data['company_id'] ?? '')));
$response = ['status' => 'error', 'message' => 'Invalid request'];
$poEsc = function ($value) use ($sql) { return mysqli_real_escape_string($sql, trim((string)$value)); };
$validDate = function ($value) { return is_string($value) && preg_match('/^\d{4}-\d{2}-\d{2}$/', $value) && strtotime($value) !== false; };

if ($company_id === '') {
    $response = ['status' => 'error', 'message' => 'Company ID is required'];
} else switch ($type) {
    case 1: // Create order and line snapshots; inventory remains unchanged until receipt.
        $vendor_id = intval($data['vendor_id'] ?? 0);
        $generated_by = $poEsc($data['generated_by'] ?? '');
        $warehouse_id = intval($data['warehouse_id'] ?? 0);
        $order_date = $poEsc($data['order_date'] ?? $date);
        $expected_date = trim((string)($data['expected_delivery_date'] ?? ''));
        $items = $data['items'] ?? [];
        if ($vendor_id <= 0 || $generated_by === '' || $warehouse_id <= 0 || !$validDate($order_date) || ($expected_date !== '' && !$validDate($expected_date)) || !is_array($items) || count($items) === 0) {
            $response = ['status' => 'error', 'message' => 'Enter a valid order date, vendor, employee, warehouse and at least one material']; break;
        }
        $vendor = mysqli_query($sql, "SELECT vendor_id FROM tbl_vendor WHERE company_id='$company_id' AND vendor_id='$vendor_id' AND is_deleted='1' AND status='Active' LIMIT 1");
        $employee = mysqli_query($sql, "SELECT emp_id FROM tbl_employee WHERE company_id='$company_id' AND emp_id='$generated_by' AND is_deleted='1' AND status='Active' LIMIT 1");
        $warehouse = mysqli_query($sql, "SELECT warehouse_id FROM tbl_warehouse WHERE company_id='$company_id' AND warehouse_id='$warehouse_id' AND is_deleted='1' AND status='Active' LIMIT 1");
        if (!$vendor || mysqli_num_rows($vendor) === 0) { $response = ['status'=>'error','message'=>'Select an active vendor']; break; }
        if (!$employee || mysqli_num_rows($employee) === 0) { $response = ['status'=>'error','message'=>'Select an active employee for Generated By']; break; }
        if (!$warehouse || mysqli_num_rows($warehouse) === 0) { $response = ['status'=>'error','message'=>'Select an active warehouse']; break; }

        $lines = []; $subtotal = 0.0; $gst_total = 0.0;
        foreach ($items as $item) {
            $material_id = $poEsc($item['material_id'] ?? '');
            $item_type = ($item['item_type'] ?? 'raw_material') === 'product' ? 'product' : 'raw_material';
            $quantity = floatval($item['quantity'] ?? 0);
            $rate = floatval($item['rate'] ?? 0);
            $gst = floatval($item['gst_percent'] ?? 0);
            if ($material_id === '' || $quantity <= 0 || $rate < 0 || $gst < 0 || $gst > 100) continue;
            if ($item_type === 'product') {
                $material = mysqli_query($sql, "SELECT p.product_id AS rm_id,p.product_name AS rm_name,u.unit_name FROM tbl_product p LEFT JOIN tbl_unit u ON u.unit_id=p.dimension_unit_id WHERE p.company_id='$company_id' AND p.product_id='$material_id' AND p.is_deleted='1' AND p.status='Active' LIMIT 1");
            } else {
                $material = mysqli_query($sql, "SELECT r.rm_id,r.rm_name,u.unit_name FROM tbl_raw_material r LEFT JOIN tbl_unit u ON u.unit_id=r.unit_id WHERE r.company_id='$company_id' AND r.rm_id='$material_id' AND r.is_deleted='1' AND r.status='Active' LIMIT 1");
            }
            if (!$material || mysqli_num_rows($material) === 0) continue;
            $row = mysqli_fetch_assoc($material);
            $base = round($quantity * $rate, 2); $tax = round($base * $gst / 100, 2); $line_total = round($base + $tax, 2);
            $subtotal += $base; $gst_total += $tax;
            $lines[] = ['id'=>$material_id,'type'=>$item_type,'name'=>$row['rm_name'],'unit'=>$row['unit_name'] ?? '', 'qty'=>$quantity,'rate'=>$rate,'gst'=>$gst,'tax'=>$tax,'line'=>$line_total];
        }
        if (count($lines) !== count($items)) { $response = ['status'=>'error','message'=>'One or more material lines are invalid; check material, quantity, rate and GST']; break; }
        $total = round($subtotal + $gst_total, 2); $remark = $poEsc($data['remark'] ?? '');
        mysqli_begin_transaction($sql);
        $expected_sql = $expected_date === '' ? 'NULL' : "'" . $poEsc($expected_date) . "'";
        $insert = "INSERT INTO tbl_purchase_order (company_id,po_number,order_date,vendor_id,generated_by,warehouse_id,expected_delivery_date,subtotal,gst_amount,total_amount,status,remark,is_deleted,c_date)
                   VALUES ('$company_id','TEMP-0','$order_date','$vendor_id','$generated_by','$warehouse_id',$expected_sql,'$subtotal','$gst_total','$total','Pending','$remark','1','$c_date')";
        $ok = mysqli_query($sql, $insert); $purchase_order_id = $ok ? mysqli_insert_id($sql) : 0;
        $po_number = 'PO-' . date('Y') . '-' . str_pad((string)$purchase_order_id, 6, '0', STR_PAD_LEFT);
        if ($ok) $ok = mysqli_query($sql, "UPDATE tbl_purchase_order SET po_number='$po_number' WHERE company_id='$company_id' AND purchase_order_id='$purchase_order_id'");
        foreach ($lines as $line) {
            if (!$ok) break;
            $ok = mysqli_query($sql, "INSERT INTO tbl_purchase_order_item (company_id,purchase_order_id,item_type,material_id,material_name,unit_name,quantity,rate,gst_percent,gst_amount,line_total,is_deleted,c_date)
                VALUES ('$company_id','$purchase_order_id','{$line['type']}','{$line['id']}','" . $poEsc($line['name']) . "','" . $poEsc($line['unit']) . "','{$line['qty']}','{$line['rate']}','{$line['gst']}','{$line['tax']}','{$line['line']}','1','$c_date')");
        }
        if ($ok) { mysqli_commit($sql); $response = ['status'=>'success','message'=>'Purchase order created successfully','purchase_order_id'=>$purchase_order_id,'po_number'=>$po_number,'subtotal'=>round($subtotal,2),'gst_amount'=>round($gst_total,2),'total_amount'=>$total]; }
        else { mysqli_rollback($sql); error_log('Purchase order save failed: ' . mysqli_error($sql)); $response = ['status'=>'error','message'=>'Could not save purchase order']; }
        break;

    case 2: // List orders.
        $q = mysqli_query($sql, "SELECT po.*,v.vendor_name,e.name AS generated_by_name,w.warehouse_name,
                    (SELECT COUNT(*) FROM tbl_purchase p WHERE p.company_id=po.company_id AND p.purchase_order_id=po.purchase_order_id AND p.is_deleted='1') AS receipt_count,
                    (SELECT COUNT(*) FROM tbl_purchase_order_item i WHERE i.company_id=po.company_id AND i.purchase_order_id=po.purchase_order_id AND i.is_deleted='1') AS item_count
                FROM tbl_purchase_order po
                LEFT JOIN tbl_vendor v ON v.company_id=po.company_id AND v.vendor_id=po.vendor_id
                LEFT JOIN tbl_employee e ON e.company_id=po.company_id AND e.emp_id=po.generated_by
                LEFT JOIN tbl_warehouse w ON w.company_id=po.company_id AND w.warehouse_id=po.warehouse_id
                WHERE po.company_id='$company_id' AND po.is_deleted='1' ORDER BY po.order_date DESC,po.purchase_order_id DESC");
        if (!$q) { $response=['status'=>'error','message'=>'Could not load purchase orders']; break; }
        $rows=[]; while($row=mysqli_fetch_assoc($q)) { if ($row['status'] === 'Ordered') $row['status'] = 'Pending'; if ($row['status'] === 'Partially Received') $row['status'] = 'Received'; $rows[]=$row; }
        $response=['status'=>'success','message'=>'Purchase orders loaded','data'=>$rows,'total'=>count($rows)]; break;

    case 3: // One order with material lines.
        $id = intval($data['purchase_order_id'] ?? 0);
        if ($id <= 0) { $response=['status'=>'error','message'=>'Purchase order ID is required']; break; }
        $q = mysqli_query($sql, "SELECT po.*,v.vendor_name,v.phone AS vendor_phone,e.name AS generated_by_name,w.warehouse_name,
                    (SELECT COUNT(*) FROM tbl_purchase p WHERE p.company_id=po.company_id AND p.purchase_order_id=po.purchase_order_id AND p.is_deleted='1') AS receipt_count
                    FROM tbl_purchase_order po LEFT JOIN tbl_vendor v ON v.company_id=po.company_id AND v.vendor_id=po.vendor_id LEFT JOIN tbl_employee e ON e.company_id=po.company_id AND e.emp_id=po.generated_by LEFT JOIN tbl_warehouse w ON w.company_id=po.company_id AND w.warehouse_id=po.warehouse_id WHERE po.company_id='$company_id' AND po.purchase_order_id='$id' AND po.is_deleted='1' LIMIT 1");
        if (!$q || mysqli_num_rows($q) === 0) { $response=['status'=>'error','message'=>'Purchase order not found']; break; }
        $order=mysqli_fetch_assoc($q); if ($order['status'] === 'Ordered') $order['status'] = 'Pending'; if ($order['status'] === 'Partially Received') $order['status'] = 'Received'; $items=[];
        $ir=mysqli_query($sql,"SELECT purchase_order_item_id,item_type,material_id,material_name,unit_name,quantity,rate,gst_percent,gst_amount,line_total FROM tbl_purchase_order_item WHERE company_id='$company_id' AND purchase_order_id='$id' AND is_deleted='1' ORDER BY purchase_order_item_id");
        if ($ir) while($item=mysqli_fetch_assoc($ir)) $items[]=$item;
        $order['items']=$items; $response=['status'=>'success','message'=>'Purchase order details loaded','data'=>$order]; break;

    case 4: // Update purchase order status.
        $id=intval($data['purchase_order_id']??0); $status=(string)($data['status']??'');
        $allowed_statuses = ['Pending','Approved','Received','Cancelled'];
        if ($id<=0 || !in_array($status, $allowed_statuses, true)) { $response=['status'=>'error','message'=>'Choose Pending, Approved, Received or Cancelled']; break; }
        $status = $poEsc($status);
        $q=mysqli_query($sql,"UPDATE tbl_purchase_order SET status='$status',updated_at='$c_date' WHERE company_id='$company_id' AND purchase_order_id='$id' AND is_deleted='1'");
        if ($q && mysqli_affected_rows($sql)>=0) $response=['status'=>'success','message'=>'Purchase order status updated'];
        else $response=['status'=>'error','message'=>'Could not update purchase order status'];
        break;
}
echo json_encode($response);
mysqli_close($sql);
?>
